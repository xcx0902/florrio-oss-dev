/** The original client receives a complete drop catalogue, which includes
 * entries absent from the reconstructed server's finalized table. */
import { readFile, writeFile } from 'node:fs/promises';
const entities = JSON.parse(await readFile('schema/catalogs/client-gallery.json', 'utf8')).entities;
const rows = entities.filter(e => e.typeId > 0).map(entity => {
  const drops = [...entity.drops]
    .sort((a, b) => b.chance - a.chance);
  return `  ${entity.typeId}: { rarity: ${entity.rarity}, drops: [${drops.map(d => `{ petalTypeId: ${d.petalTypeId}, chance: ${d.chance} }`).join(', ')}] },`;
});
await writeFile('client/src/schema/mob-gallery.ts', `/** Generated by tools/gen-mob-gallery.mjs from the original client catalogue. */
export interface MobGalleryDrop { readonly petalTypeId: number; readonly chance: number; }
export interface MobGalleryInfo { readonly rarity: number; readonly drops: readonly MobGalleryDrop[]; }
export const MOB_GALLERY: Readonly<Record<number, MobGalleryInfo>> = {
${rows.join('\n')}
};
`);
