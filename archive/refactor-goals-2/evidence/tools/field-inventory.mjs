const SOURCE_ROOTS = ['engine', 'client', 'server', 'schema', 'tools', 'tests', 'docs'];
const ROOT_FILES = readdirSync(ROOT, { withFileTypes: true })
  .filter((entry) => entry.isFile())
  .map((entry) => path.join(ROOT, entry.name));

function walk(directory) {
  return readdirSync(directory).flatMap((name) => {
    const file = path.join(directory, name);
    return statSync(file).isDirectory() ? walk(file) : [file];
  });
}

const files = [
  ...SOURCE_ROOTS.flatMap((root) => walk(path.join(ROOT, root))),
  ...ROOT_FILES,
].filter((file) => !relative(file).startsWith('archive/'));

function relative(file) {
  return path.relative(ROOT, file).split(path.sep).join('/');
}

function read(file) {
  return readFileSync(file, 'utf8');
}

const sourceFiles = files.filter(
  (file) =>
    /\.(mjs|ts|js|json|yaml|yml|md|cpp|hpp|h|inc)$/.test(file) &&
    !relative(file).startsWith('refactor-goals/'),
);
const sourceText = new Map(sourceFiles.map((file) => [relative(file), read(file)]));

function scopeCounts(name, scopes) {
  const pattern = new RegExp(`\\b${name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`, 'g');
  return scopes.map(([label, prefix]) => {
    let total = 0;
    for (const [file, text] of sourceText) {
      if (!file.startsWith(prefix)) {
        continue;
      }
      if (file === 'schema/catalogs/entities.json' && name === 'name') {
        continue;
      }
      total += text.match(pattern)?.length ?? 0;
    }
    return [label, total];
  });
}

function formatCounts(counts) {
  return counts.map(([label, value]) => `${label} ${value}`).join(' / ');
}

function catalogDisposition(source, field) {
  const key = `${path.basename(source, '.json')}/${field}`;
  if (DELETE_SCHEMA_FIELDS.has(key)) {
    return '删除（P3）';
  }
  if (REPLACE_FIELDS.has(key)) {
    return '替换为行为类型（P3）';
  }
  if (RENAME_FIELDS.has(key)) {
    return '保留并改名（P3）';
  }
  const counts = scopeCounts(field, SCOPES);
  const total = counts.reduce((sum, [, value]) => sum + value, 0);
  if (total === 0) {
    return '删除候选：无引用（P3 复核生成消费者）';
  }
  return '保留：catalog/派生数据输入（P3 复核）';
}

const SCOPES = [
  ['schema', 'schema/'],
  ['tools', 'tools/'],
  ['engine', 'engine/src/'],
  ['engine-include', 'engine/include/'],
  ['client', 'client/src/'],
  ['tests', 'tests/'],
  ['client-tests', 'client/tests/'],
];

function extractCppStructs() {
  const structs = [];
  for (const file of files.filter((file) => /engine\/include\/.*\.(hpp|h)$/.test(file)).sort()) {
    const name = relative(file);
    if (GENERATED_HEADERS.has(name)) {
      continue;
    }
    const lines = read(file).split('\n');
    let current = null;
    let depth = 0;
    for (const line of lines) {
      const start = line.match(/^\s*(?:struct|class)\s+(\w+)(?:\s*:[^{]+)?\s*\{\s*$/);
      if (start) {
        current = { name: start[1], file: name, fields: [] };
        depth = 1;
        continue;
      }
      if (!current) {
        continue;
      }
      depth += (line.match(/\{/g) ?? []).length - (line.match(/\}/g) ?? []).length;
      if (depth <= 0) {
        structs.push(current);
        current = null;
        continue;
      }
      if (depth !== 1) {
        continue;
      }
      let text = line.trim();
      if (
        !text ||
        /^(?:\/\/|\/\*|\*|#|static\b|friend\b|typedef\b|using\b|enum\b|struct\b|class\b|template\b|public:|private:|protected:)/.test(
          text,
        )
      ) {
        continue;
      }
      if (/\([^;]*\)\s*(?:const\s*)?(?:noexcept\s*)?(?:;|\{|=\s*(?:default|delete))/.test(text)) {
        continue;
      }
      text = text.replace(/\[\[[^\]]*\]\]\s*/g, '').replace(/\s*\/\/.*$/, '');
      const match = text.match(
        /^(?:const\s+|mutable\s+)?([\w:<>,\s*&]+?)\s+(\w+)(?:\s*\[[^\]]*\])?\s*(?::\s*\d+)?\s*(?:=\s*[^;]*|\{[^}]*\})?;\s*$/,
      );
      if (match) {
        current.fields.push({ type: match[1].trim(), name: match[2] });
      }
    }
  }
  return structs;
}

function runtimeDisposition(struct, field) {
  const key = `${struct}/${field}`;
  if (DELETE_RUNTIME_FIELDS.has(key)) {
    return '删除（P3/P6）';
  }
  if (REPLACE_RUNTIME_FIELDS.has(key)) {
    return '替换为当前行为类型（P3）';
  }
  if (RENAME_RUNTIME_FIELDS.has(key)) {
    return '保留并改名（P3）';
  }
  const counts = scopeCounts(field, [
    ['src', 'engine/src/'],
    ['include', 'engine/include/'],
    ['tests', 'engine/tests/'],
  ]);
  // The declaration itself is one include hit; only further uses count.
  const engine = counts[0][1] + Math.max(0, counts[1][1] - 1);
  const tests = counts[2][1];
  if (engine === 0 && tests === 0) {
    return '删除候选：活动代码无文本引用（P3 复核导出与聚合初始化）';
  }
  return '保留（P3 复核命名与单位）';
}

function extractTsInterfaces() {
  const result = [];
  for (const file of files.filter((file) => /client\/src\/.*\.ts$/.test(file)).sort()) {
    const name = relative(file);
    if (name.startsWith('client/src/schema/')) {
      continue;
    }
    const text = read(file);
    const regex = /export interface (\w+)(?: extends [^{]+)? \{([\s\S]*?)\n\}/g;
    for (const match of text.matchAll(regex)) {
      const fields = [];
      for (const line of match[2].split('\n')) {
        const field = line.match(/^\s+(?:readonly\s+)?(\w+)(\?)?:/);
        if (field) {
          fields.push(field[1]);
        }
      }
      result.push({ name: match[1], file: name, fields });
    }
  }
  return result;
}

function protocolRows(inputs) {
  const { contract } = validateInputs(inputs);
  const dense = new Map();
  for (const group of contract.denseGroups) {
    for (const field of group.fields) {
      dense.set(field, group.component);
    }
  }
  return contract.fields.map((field) => {
    const pattern = new RegExp(`\\bfield${field.id}\\b`, 'g');
    let engine = 0;
    let client = 0;
    for (const [file, text] of sourceText) {
      if (file.startsWith('engine/src/')) {
        engine += text.match(pattern)?.length ?? 0;
      }
      if (file.startsWith('client/src/')) {
        client += text.match(pattern)?.length ?? 0;
      }
    }
    return {
      id: field.id,
      type: field.type,
      component: dense.get(field.id) ?? '',
      dense: dense.get(field.id) ?? '',
      engine,
      client,
    };
  });
}

const lines = [];
lines.push(EVIDENCE_HEADER);
lines.push('# P0 字段清单（附录）\n');
lines.push(
  '本文件由 `refactor-goals/evidence/tools/field-inventory.mjs` 从当前源码生成，逐字段列出定义位置、引用分布和处置。计数是文本引用量，不是读写语义；结论结合人工核对的消费者判断。\n',
);
lines.push(`生成时间：${new Date().toISOString()}。活动源码文件：${sourceFiles.length}。\n`);

lines.push('## 1. catalog 输入字段\n');
for (const [file, collection, label] of CATALOG_SOURCES) {
  const json = JSON.parse(read(file));
  const record = json[collection]?.[0];
  if (!record) {
    continue;
  }
  lines.push(`### ${label}（\`${file}\` → \`${collection}[]\`）\n`);
  lines.push('| 字段 | 类型 | 引用（schema/tools/engine/client） | 处置 |');
  lines.push('| --- | --- | --- | --- |');
  for (const [field, value] of Object.entries(record)) {
    const counts = scopeCounts(field, SCOPES);
    const type = Array.isArray(value) ? 'array' : typeof value;
    lines.push(
      `| \`${field}\` | ${type} | ${formatCounts(counts)} | ${catalogDisposition(file, field)} |`,
    );
  }
  lines.push('');
}

lines.push('## 2. 手写 C++ 模型字段\n');
lines.push('生成头文件不在此表重复；它们由上面的 catalog 与 protocol 输入派生。\n');
for (const struct of extractCppStructs()) {
  if (!struct.fields.length) {
    continue;
  }
  lines.push(`### \`${struct.name}\`（\`${struct.file}\`）\n`);
  lines.push('| 字段 | 类型 | engine 引用（src+include，声明不计） | engine/tests 引用 | 处置 |');
  lines.push('| --- | --- | --- | --- | --- |');
  for (const field of struct.fields) {
    const [src, include, tests] = scopeCounts(field.name, [
      ['src', 'engine/src/'],
      ['include', 'engine/include/'],
      ['tests', 'engine/tests/'],
    ]);
    lines.push(
      `| \`${field.name}\` | \`${field.type}\` | ${src[1] + Math.max(0, include[1] - 1)} | ${tests[1]} | ${runtimeDisposition(struct.name, field.name)} |`,
    );
  }
  lines.push('');
}

lines.push('## 3. 客户端状态接口字段\n');
for (const iface of extractTsInterfaces()) {
  if (!iface.fields.length) {
    continue;
  }
  lines.push(`### \`${iface.name}\`（\`${iface.file}\`）\n`);
  lines.push('| 字段 | client/src 引用 | client/tests 引用 | 处置 |');
  lines.push('| --- | --- | --- | --- |');
  for (const field of iface.fields) {
    const counts = scopeCounts(field, [
      ['src', 'client/src/'],
      ['tests', 'client/tests/'],
    ]);
    lines.push(`| \`${field}\` | ${counts[0][1]} | ${counts[1][1]} | 保留（P4 复核协议来源） |`);
  }
  lines.push('');
}

lines.push('## 4. 协议 sparse 字段\n');
lines.push(
  '字段名尚不存在：当前运行时按编号访问。全部行在 P4 迁移到当前组件标识；此处登记编号、类型、组件归属和当前访问量。\n',
);
lines.push('| 字段 | 类型 | 组件 | dense 组 | snapshot_codec 访问 | projection 访问 | 处置 |');
lines.push('| --- | --- | --- | --- | --- | --- | --- |');
const inputs = await loadSchemaInputs(ROOT);
for (const row of protocolRows(inputs)) {
  lines.push(
    `| ${row.id} | ${row.type} | ${row.component || '—'} | ${row.dense || '—'} | ${row.engine} | ${row.client} | P4 迁移 |`,
  );
}
lines.push('');

lines.push('## 5. 多人协议记录\n');
const multiplayer = YAML.parse(read('schema/multiplayer.yaml'));
for (const [name, record] of Object.entries(multiplayer.records ?? {})) {
  lines.push(
    `### \`${name}\`${multiplayer.messages?.[name] ? `（message ${multiplayer.messages[name].id}）` : ''}\n`,
  );
  lines.push(
    `字段：${Object.keys(record)
      .map((field) => `\`${field}\``)
      .join('、')}。\n`,
  );
  lines.push('处置：保留，P4 按当前组件/消息模型复核。\n');
}

process.stdout.write(`${lines.join('\n')}\n`);
