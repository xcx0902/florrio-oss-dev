/** Real pointer evidence from the frozen original, with a virtual frame clock. */
import http from 'node:http';
import path from 'node:path';
import { readFile, writeFile } from 'node:fs/promises';
import { chromium } from 'playwright-core';
import { pathToFileURL } from 'node:url';
const { chromiumExecutable } = await import(pathToFileURL(path.resolve('tools/lib/chromium.mjs')).href);
const { loadOriginal } = await import(pathToFileURL(path.resolve('test/helpers/wasm-probe.mjs')).href);
const oracle = await loadOriginal('client', { functionIds: [368, 1102] });
const discovery = oracle.call(368, 12);
oracle.call(1102, discovery, 1);
const basicDiscovery = new TextDecoder().decode(new Uint8Array(oracle.memory.buffer, discovery, 8));

const root = path.resolve('legacy/web');
const mime = { '.html': 'text/html', '.js': 'text/javascript', '.wasm': 'application/wasm', '.css': 'text/css', '.woff2': 'font/woff2' };
const server = http.createServer(async (request, response) => {
  try {
    const pathname = new URL(request.url, 'http://local.test').pathname;
    const filename = path.resolve(root, '.' + (pathname === '/' ? '/index.html' : pathname));
    if (!filename.startsWith(root + path.sep)) { response.writeHead(403).end(); return; }
    response.writeHead(200, { 'Content-Type': mime[path.extname(filename)] ?? 'application/octet-stream' }).end(await readFile(filename));
  } catch { response.writeHead(404).end(); }
});
await new Promise((resolve, reject) => { server.once('error', reject); server.listen(0, '127.0.0.1', resolve); });
const browser = await chromium.launch({ executablePath: chromiumExecutable(), headless: true });
const results = [];
try {
  for (const viewport of [{ width: 1280, height: 720 }, { width: 1440, height: 900 }, { width: 1920, height: 1080 }, { width: 1024, height: 768 }]) {
    const context = await browser.newContext({ viewport });
    const page = await context.newPage();
    await page.addInitScript({ content: (await readFile('tools/parity/virtual-clock.js', 'utf8')).replace(/^export function /gm, 'function ') + '\ninstallVirtualClock();' });
    await page.addInitScript(value => localStorage.setItem('gallery_1', value), basicDiscovery);
    await page.goto(`http://127.0.0.1:${server.address().port}/index.html`);
    await page.waitForFunction(() => !!window.Module?.HEAPU32);
    await page.evaluate(() => window.__virtualClock.runFrames(90));
    const scale = Math.fround(Math.max(0.7, Math.fround(Math.max(viewport.width * 0.000521, viewport.height * 0.000926))));
    const height = Math.ceil(Math.fround(viewport.height / scale));
    const result = { viewport, scale, height, tabs: [] };
    for (const [label, x] of [['Settings', 60], ['Petals', 170], ['Mobs', 280], ['Changelog', 400]]) {
      const point = { x: x * scale, y: (height - 27.5) * scale };
      await page.mouse.move(point.x, point.y);
      await page.evaluate(() => window.__virtualClock.runFrames(3));
      const cursor = await page.locator('#canvas').evaluate(canvas => getComputedStyle(canvas).cursor);
      await page.mouse.down();
      await page.evaluate(() => window.__virtualClock.runFrames(3));
      await page.mouse.up();
      await page.evaluate(() => window.__virtualClock.runFrames(20));
      result.tabs.push({ label, point, cursor, nativePanel: await page.evaluate(() => window.Module.HEAPU32[7926848 / 4]) });
    }
    await page.mouse.move(170 * scale, (height - 27.5) * scale);
    await page.evaluate(() => window.__virtualClock.runFrames(3));
    await page.mouse.down();
    await page.evaluate(() => window.__virtualClock.runFrames(3));
    await page.mouse.up();
    await page.evaluate(() => window.__virtualClock.runFrames(30));
    result.gallery = [];
    result.galleryPanel = await page.evaluate(() => window.Module.HEAPU32[7926848 / 4]);
    for (const point of [{ x: 65 * scale, y: (height - 331) * scale },
      { x: 70 * scale, y: (height - 326) * scale }, { x: 135 * scale, y: (height - 331) * scale }]) {
      await page.mouse.move(point.x, point.y);
      await page.evaluate(() => window.__virtualClock.runFrames(10));
      result.gallery.push({ point, cursor: await page.locator('#canvas').evaluate(canvas => getComputedStyle(canvas).cursor) });
    }
    if (viewport.width === 1280) await page.screenshot({ path: path.resolve('reports/menu-click-repair/native-gallery.png') });
    results.push(result);
    await context.close();
  }
  await writeFile(new URL('./native-menu.json', import.meta.url), JSON.stringify({
    oracle: 'legacy/web/client.wasm',
    sha256: 'c1e574288f05e4387c888e375952f0b61a1a5f185cef25ad74d0c1088759a4b1',
    method: 'Native browser mouse input; only read native current-panel field. Virtual clock 16ms frames. Saved Basic discovery fixture generated by original func1102; no discovery bits patched.',
    results,
  }, null, 2) + '\n');
  console.log(JSON.stringify(results));
} finally {
  await browser.close();
  server.closeAllConnections();
  await new Promise(resolve => server.close(resolve));
}
