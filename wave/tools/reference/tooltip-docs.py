def escaped(value):
    return str(value).replace('|', '\\|').replace('\n', '<br>')


def cell(field):
    if field is None:
        return '—'
    display = field['display']
    exact = field.get('range', field['value'])
    # Retain the human-readable original rendering; all exact formatter inputs
    # remain in the adjacent JSON, including noninteger binary32 values.
    if isinstance(exact, list):
        precise = '~'.join(str(v) for v in exact)
    elif isinstance(exact, (float, int)):
        precise = str(exact)
        if float(exact).is_integer():
            precise = str(int(exact))
    else:
        precise = ''
    suffix = ''
    if precise and (('k' in display or 'm' in display) or
                    (isinstance(exact, float) and not exact.is_integer())):
        suffix = '<br>原值 ' + precise
    if 'perSecond' in field:
        suffix += '<br>原速率 ' + str(field['perSecond']) + '/s'
    return escaped(display) + escaped(suffix)


def drop_tables(entry, petals):
    variants = entry['variants']
    lines = ['掉落面板（列为怪物稀有度，行为产物稀有度）：', '']
    if entry['dropInheritanceId'] or entry['galleryParentId']:
        lines += [f'原记录的掉落继承 ID：`{entry["dropInheritanceId"]}`；图鉴父 ID：`{entry["galleryParentId"]}`。下表保留此 ID 自身缓存的面板，不将分节视为额外掉落机会。', '']
    if not entry['loot']:
        return lines + ['六个稀有度的自身掉落面板均为空；没有可从此记录计算的掉落项。', '']
    for loot in entry['loot']:
        petal_id = loot['petalId']
        petal = petals[petal_id]
        lines += [f'产物 **[{petal["name"]}](#petal-{petal_id})**（ID {petal_id}；原 f32 系数 `{loot["coefficient"]}`）：', '',
                  '| 产物稀有度 | ' + ' | '.join(v['name'] for v in variants) + ' |',
                  '| --- | ' + ' | '.join('---' for _ in variants) + ' |']
        for rarity in range(6):
            cells = [variants[rarity]['name']]
            for variant in variants:
                drop = next(d for d in variant['drops']['candidates']
                            if (d['petalId'], d['rarity']) == (petal_id, rarity))
                cells.append(drop['display'] if drop['displayed'] else
                             '不可用' if drop['probability'] is None else
                             '0（不显示）' if drop['probability'] == 0 else '<0.01%（隐藏）')
            lines.append('| ' + ' | '.join(cells) + ' |')
        lines.append('')
    return lines


