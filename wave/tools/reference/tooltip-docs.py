def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = json.loads(DATA.read_text())
    catalog = json.loads((DATA.parent / 'catalog.json').read_text())
    text = render(data, catalog)
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != text:
            raise SystemExit('tooltip documentation is stale')
    else:
        OUTPUT.write_text(text)
    print('Tooltip documentation: 45 petals, 35 mob IDs, all six rarities ' + ('verified' if args.check else 'written'))


if __name__ == '__main__':
    main()
