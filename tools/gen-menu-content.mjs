#!/usr/bin/env node
/** Read the frozen client constructor's changelog table; never start main,
 * timers, rendering or networking. Nf and Mf are the archived init/memory
 * exports, also used by source/semantic/extract-client-catalogs.mjs.
 * WAT initializeClientRuntimeAndPetalCatalog stores 35 records at 165440,
 * stride 72: date pointer +0, note count u8 +4, note pointers +8.
 */
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const output = new URL('client/src/schema/menu-content.ts', root);

export async function extractMenuContent() {
  const bytes = await readFile(new URL('web/client.wasm', root));
  const module = new WebAssembly.Module(bytes), imports = {};
  for (const item of WebAssembly.Module.imports(module)) {
    if (item.kind !== 'function') throw new Error(`Unexpected import: ${item.kind}`);
    (imports[item.module] ??= {})[item.name] = () => 0;
  }
  const wasm = new WebAssembly.Instance(module, imports).exports;
  wasm.Nf();
  const memory = new Uint8Array(wasm.Mf.buffer), view = new DataView(memory.buffer);
  const string = pointer => {
    const end = memory.indexOf(0, pointer);
    if (!pointer || pointer >= memory.length || end < pointer) throw new Error(`Invalid string pointer ${pointer}`);
    return new TextDecoder('utf-8', { fatal: true }).decode(memory.subarray(pointer, end));
  };
  const entries = Array.from({ length: 35 }, (_, index) => {
    const address = 165440 + index * 72, count = memory[address + 4];
    const date = string(view.getUint32(address, true));
    if (!/^[A-Z][a-z]+ \d+(?:st|nd|rd|th) 2020$/.test(date) || count < 1 || count > 16)
      throw new Error(`Unexpected changelog record at ${address}`);
    const notes = Array.from({ length: count }, (_, note) => string(view.getUint32(address + 8 + note * 4, true)));
    return { date, notes };
  });
  return { sha256: createHash('sha256').update(bytes).digest('hex'), entries };
}

export function menuContentSource({ sha256, entries }) {
  return `// Generated by tools/gen-menu-content.mjs from frozen web/client.wasm.
// SHA-256: ${sha256}
// WAT initializeClientRuntimeAndPetalCatalog: 165440 + index * 72 (35 records).
// Preserve table order, repeated dates, punctuation and embedded newlines.
export interface ChangelogEntry {
  readonly date: string;
  readonly notes: readonly string[];
}

export const CHANGELOG: readonly ChangelogEntry[] = ${JSON.stringify(entries, null, 2)};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const data = await extractMenuContent(), source = menuContentSource(data);
  if (process.argv.includes('--verify')) {
    if (await readFile(output, 'utf8') !== source) throw new Error('Menu content differs from frozen client; run node tools/gen-menu-content.mjs');
  } else await writeFile(output, source);
  console.log(JSON.stringify({ entries: data.entries.length,
    notes: data.entries.reduce((count, entry) => count + entry.notes.length, 0),
    sha256: data.sha256, verified: process.argv.includes('--verify') }));
}
