#!/usr/bin/env node
/**
 * Generate client/src/schema/menu-content.ts from the project CHANGELOG.md.
 *
 * The in-game Changelog panel must describe this reconstruction, not the frozen
 * 2020 upstream client. CHANGELOG.md is the single human-editable source.
 */
import { readFile, writeFile } from 'node:fs/promises';

const markdown = await readFile('CHANGELOG.md', 'utf8');
const entries = [];
let current = null;
let section = '';
let lastNote = null;

for (const raw of markdown.split('\n')) {
  const line = raw.replace(/\r$/, '');
  const release = line.match(/^##\s+(?:\[([^\]]+)\](?:\s+-\s+(\d{4}-\d{2}-\d{2}))?|(.+?))\s*$/);
  if (release) {
    const name = (release[1] ?? release[3] ?? '').trim();
    const date = release[2] ? `${name} - ${release[2]}` : name;
    current = { date, notes: [] };
    entries.push(current);
    section = '';
    lastNote = null;
    continue;
  }
  const heading = line.match(/^###\s+(.+?)\s*$/);
  if (heading) {
    section = heading[1].trim();
    lastNote = null;
    continue;
  }
  const bullet = line.match(/^-\s+(.+?)\s*$/);
  if (bullet && current) {
    const clean = bullet[1].replace(/`([^`]+)`/g, '$1');
    const note = section ? `${section}: ${clean}` : clean;
    current.notes.push(note);
    lastNote = note;
    continue;
  }
  const continuation = line.match(/^\s{2,}(.+?)\s*$/);
  if (continuation && current && lastNote) {
    current.notes[current.notes.length - 1] = `${lastNote} ${continuation[1]}`;
    lastNote = current.notes[current.notes.length - 1];
    continue;
  }
  if (line.trim() === '') lastNote = null;
}

for (const entry of entries) entry.notes = entry.notes.map(note => note.replace(/`/g, ''));
const usable = entries.filter(entry => entry.notes.length > 0);
if (usable.length === 0) throw new Error('CHANGELOG.md has no release entries with notes');
for (const entry of usable) {
  if (!entry.date || !entry.notes.every(note => note.length > 0))
    throw new Error(`invalid changelog entry: ${entry.date}`);
}

const body = usable.map(entry => `  {\n    "date": ${JSON.stringify(entry.date)},\n    "notes": [\n${entry.notes.map(note => `      ${JSON.stringify(note)}`).join(',\n')}\n    ]\n  }`).join(',\n');
const output = `// Generated by tools/gen-menu-content.mjs from CHANGELOG.md. Do not edit.
// Edit CHANGELOG.md and rerun \`npm run gen:menu-content\`.
export interface ChangelogEntry {
  readonly date: string;
  readonly notes: readonly string[];
}

export const CHANGELOG: readonly ChangelogEntry[] = [
${body}
];
`;
await writeFile('client/src/schema/menu-content.ts', output);
console.log(`menu-content: ${usable.length} entries, ${usable.reduce((sum, entry) => sum + entry.notes.length, 0)} notes`);
