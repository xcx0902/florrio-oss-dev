#!/usr/bin/env node
/**
 * Generate `client/src/schema/petals.ts` from the recovered petal catalog.
 * The HUD tooltip needs the original names, rarities, reload times and
 * descriptions; keeping the table generated avoids a second hand-maintained
 * copy of the catalog.
 */
import { readFile, writeFile } from 'node:fs/promises';

const catalog = JSON.parse(await readFile('schema/catalogs/petals.json', 'utf8'));
const combat = JSON.parse(await readFile('schema/catalogs/petal-combat.json', 'utf8'));
const mobs = JSON.parse(await readFile('schema/catalogs/entities.json', 'utf8'));
const entries = catalog.petals.map(petal => {
  const description = (petal.descriptions ?? []).find(text => text.length > 0) ?? '';
  return `  ${petal.typeId}: { name: ${JSON.stringify(petal.name)}, rarity: ${petal.rarityIndex}, `
    + `recharge: ${petal.rechargeMilliseconds}, radius: ${combat.petals.find(row => row.typeId === petal.typeId)?.collisionRadius || 10}, labelSize: ${petal.radius}, instances: ${petal.instancesPerSlot}, description: ${JSON.stringify(description)} },`;
});
const source = `// Generated by tools/gen-client-petals.mjs from schema/catalogs/petals.json.
// Do not edit by hand; rerun \`node tools/gen-client-petals.mjs\`.
export interface PetalInfo {
  readonly name: string;
  readonly rarity: number;
  readonly recharge: number;
  readonly radius: number;
  /** Native card-label font unit (definition radius, not collision radius). */
  readonly labelSize: number;
  readonly instances: number;
  readonly description: string;
}

export const PETAL_INFO: Readonly<Record<number, PetalInfo>> = {
${entries.join('\n')}
};

export const RARITY_NAMES: readonly string[] = [
  'Common', 'Unusual', 'Rare', 'Epic', 'Legendary', 'Unique', 'Ultra', 'Super',
];

export const MOB_INFO: Readonly<Record<number, { readonly name: string; readonly description: string }>> = {
${mobs.entities.map(mob => `  ${mob.typeId}: { name: ${JSON.stringify(mob.name)}, description: ${JSON.stringify(mob.descriptions.join(' '))} },`).join('\n')}
};
`;
await writeFile('client/src/schema/petals.ts', source);
console.log(JSON.stringify({ petals: catalog.petals.length, bytes: source.length }));
