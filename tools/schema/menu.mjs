/** Product menu content: CHANGELOG.md is the only human-editable source. */

const fail = message => { throw new Error(`menu content: ${message}`); };

/** Parse the project changelog into release entries with notes. */
export function parseChangelog(markdown) {
  if (typeof markdown !== 'string' || markdown.trim().length === 0)
    fail('CHANGELOG.md is empty');
  const entries = [];
  let current = null;
  let section = '';
  let lastNote = null;
  for (const raw of markdown.split('\n')) {
    const line = raw.replace(/\r$/, '');
    const release = line.match(/^##\s+(?:\[([^\]]+)\](?:\s+-\s+(\d{4}-\d{2}-\d{2}))?|(.+?))\s*$/);
    if (release) {
      const name = (release[1] ?? release[3] ?? '').trim();
      if (name.length === 0) fail('release heading has no version name');
      const date = release[2] ? `${name} - ${release[2]}` : name;
      current = { date, notes: [] };
      entries.push(current);
      section = '';
      lastNote = null;
      continue;
    }
    const heading = line.match(/^###\s+(.+?)\s*$/);
    if (heading) {
      section = heading[1].trim();
      if (section.length === 0) fail('section heading is empty');
      lastNote = null;
      continue;
    }
    const bullet = line.match(/^-\s+(.+?)\s*$/);
    if (bullet) {
      if (!current) fail(`release notes before a release heading: ${line}`);
      const clean = bullet[1].replace(/`([^`]+)`/g, '$1').trim();
      if (clean.length === 0) fail('release note is empty');
      const note = section ? `${section}: ${clean}` : clean;
      current.notes.push(note);
      lastNote = note;
      continue;
    }
    const continuation = line.match(/^\s{2,}(.+?)\s*$/);
    if (continuation) {
      if (!current || !lastNote) fail(`continuation without a release note: ${line}`);
      current.notes[current.notes.length - 1] = `${lastNote} ${continuation[1]}`;
      lastNote = current.notes[current.notes.length - 1];
      continue;
    }
    if (line.trim() === '') lastNote = null;
  }
  if (entries.length === 0) fail('CHANGELOG.md has no release headings');
  for (const entry of entries) {
    if (entry.notes.length === 0) fail(`release ${entry.date} has no notes`);
    if (entry.notes.some(note => note.length === 0)) fail(`release ${entry.date} has an empty note`);
  }
  return entries;
}

export function generateMenuContent(markdown) {
  const usable = parseChangelog(markdown);
  const body = usable.map(entry => `  {\n    "date": ${JSON.stringify(entry.date)},\n    "notes": [\n${entry.notes.map(note => `      ${JSON.stringify(note)}`).join(',\n')}\n    ]\n  }`).join(',\n');
  return `// Generated by tools/generate.mjs from CHANGELOG.md. Do not edit.
// Edit CHANGELOG.md and rerun \`npm run schema:generate\`.
export interface ChangelogEntry {
  readonly date: string;
  readonly notes: readonly string[];
}

export const CHANGELOG: readonly ChangelogEntry[] = [
${body}
];
`;
}
