/** Product packet-key validation and rendering. Pure functions only. */

const HEX = /^[0-9a-fA-F]+$/;
const fail = message => { throw new Error(`transport: ${message}`); };

function integer(value, label, minimum, maximum) {
  if (!Number.isInteger(value) || value < minimum || value > maximum)
    fail(`${label} must be an integer ${minimum}..${maximum}`);
  return value;
}

/** Validate the product transport document and return the decoded key bytes. */
export function validateTransport(transport) {
  if (transport === null || typeof transport !== 'object' || Array.isArray(transport))
    fail('document must be an object');
  integer(transport.schema, 'schema', 1, 1);
  integer(transport.protocolVersion, 'protocolVersion', 1, 0xffff);
  if (typeof transport.purpose !== 'string' || transport.purpose.length === 0)
    fail('purpose must be a nonempty string');
  const packetXor = transport.packetXor;
  if (packetXor === null || typeof packetXor !== 'object' || Array.isArray(packetXor))
    fail('packetXor must be an object');
  if (packetXor.algorithm !== 'xor') fail('packetXor.algorithm must be xor');
  if (packetXor.encoding !== 'hex') fail('packetXor.encoding must be hex');
  integer(packetXor.bytes, 'packetXor.bytes', 256, 256);
  if (typeof packetXor.keyHex !== 'string') fail('packetXor.keyHex must be a string');
  if (packetXor.keyHex.length !== 512)
    fail(`packetXor.keyHex must contain exactly 512 hex characters, found ${packetXor.keyHex.length}`);
  if (!HEX.test(packetXor.keyHex)) fail('packetXor.keyHex contains a non-hex character');
  const bytes = Uint8Array.from(packetXor.keyHex.match(/../g).map(value => Number.parseInt(value, 16)));
  if (bytes.length !== 256) fail(`decoded packet key must be 256 bytes, found ${bytes.length}`);
  return bytes;
}

/** XOR a copy of `input` with the repeating product key. */
export function applyPacketXor(input, key) {
  const output = Uint8Array.from(input);
  for (let index = 0; index < output.length; ++index)
    output[index] ^= key[index % key.length];
  return output;
}

function hex(bytes) {
  return [...bytes].map(value => '0x' + value.toString(16).padStart(2, '0')).join(', ');
}

export function generatePacketKeyHeader(bytes) {
  const lines = [
    '// Generated by tools/generate.mjs from schema/transport.json. Do not edit.',
    '#pragma once',
    '#include <array>',
    '#include <cstdint>',
    '',
    'namespace engine::net {',
    'inline constexpr std::array<std::uint8_t, 256> kPacketXorKey = {',
  ];
  for (let index = 0; index < bytes.length; index += 16)
    lines.push(`  ${hex(bytes.slice(index, index + 16))},`);
  lines.push('};', '} // namespace engine::net');
  return lines.join('\n') + '\n';
}

export function generatePacketKeyTs(bytes) {
  const lines = [
    '// Generated by tools/generate.mjs from schema/transport.json. Do not edit.',
    'export const PACKET_XOR_KEY: Uint8Array = Uint8Array.from([',
  ];
  for (let index = 0; index < bytes.length; index += 16)
    lines.push(`  ${hex(bytes.slice(index, index + 16))},`);
  lines.push(']);');
  return lines.join('\n') + '\n';
}
