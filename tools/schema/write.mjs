/** Write/check generated outputs. The manifest is the only obsolete-file ledger. */
import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { OUTPUT_MANIFEST, GENERATOR } from './outputs.mjs';
import { SCHEMA_INPUTS } from './load.mjs';

const hash = value => createHash('sha256').update(value).digest('hex');
const GENERATED_HEADER = /Generated by tools\/generate\.mjs/;
const SCAN_ROOTS = ['schema/generated', 'schema/catalogs', 'engine/include/engine/net',
  'engine/include/engine/catalog', 'client/src/schema', 'docs'];

export function manifestFor(outputs) {
  const rows = [...outputs].sort(([left], [right]) => left.localeCompare(right));
  return {
    schema: 2,
    generatedBy: GENERATOR,
    inputs: Object.values(SCHEMA_INPUTS),
    outputs: rows.map(([file, content]) => ({
      path: file, bytes: Buffer.byteLength(content), sha256: hash(content),
    })),
  };
}

function resolveInside(root, relative) {
  const absolute = path.resolve(root, relative);
  if (absolute !== root && !absolute.startsWith(root + path.sep))
    throw new Error(`generated path escapes the product root: ${relative}`);
  return absolute;
}

async function readOrNull(filename) {
  try { return await readFile(filename, 'utf8'); }
  catch (error) { if (error.code === 'ENOENT') return null; throw error; }
}

async function walk(directory) {
  let entries;
  try { entries = await readdir(directory, { withFileTypes: true }); }
  catch (error) { if (error.code === 'ENOENT') return []; throw error; }
  const files = [];
  for (const entry of entries) {
    const filename = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(filename));
    else if (entry.isFile()) files.push(filename);
  }
  return files;
}

/** Generated files on disk that the current generator does not own. */
export async function unexpectedGeneratedFiles(root, outputs) {
  const expected = new Set([...outputs.keys()].map(file => path.resolve(root, file)));
  const extras = [];
  for (const relative of SCAN_ROOTS) {
    for (const filename of await walk(path.resolve(root, relative))) {
      if (expected.has(filename)) continue;
      if (!/\.(hpp|ts|json|md)$/.test(filename)) continue;
      const head = (await readFile(filename, 'utf8')).slice(0, 300);
      if (GENERATED_HEADER.test(head)) extras.push(path.relative(root, filename));
    }
  }
  return extras.sort();
}

/** Read-only consistency check. Throws with the first concrete failure. */
export async function checkOutputs(root, outputs) {
  for (const [relative, expected] of outputs) {
    const actual = await readOrNull(resolveInside(root, relative));
    if (actual === null) throw new Error(`missing generated output: ${relative}`);
    if (actual !== expected) throw new Error(`generated output is stale: ${relative}`);
  }
  const manifestPath = resolveInside(root, OUTPUT_MANIFEST);
  const raw = await readOrNull(manifestPath);
  if (raw === null) throw new Error(`missing generated output manifest: ${OUTPUT_MANIFEST}`);
  let stored;
  try { stored = JSON.parse(raw); }
  catch { throw new Error(`invalid generated output manifest: ${OUTPUT_MANIFEST}`); }
  const expected = manifestFor(outputs);
  if (JSON.stringify(stored) !== JSON.stringify(expected))
    throw new Error(`generated output manifest is stale: ${OUTPUT_MANIFEST}`);
  const owned = new Set(expected.outputs.map(entry => entry.path));
  for (const entry of stored.outputs) {
    if (!owned.has(entry.path))
      throw new Error(`obsolete generated output is still registered: ${entry.path}`);
  }
  const extras = await unexpectedGeneratedFiles(root, outputs);
  if (extras.length) throw new Error(`unregistered generated output: ${extras.join(', ')}`);
  return expected.outputs.length;
}

/** Compute all contents first, then write. Removes only manifest-registered stale files. */
export async function writeOutputs(root, outputs) {
  const oldRaw = await readOrNull(resolveInside(root, OUTPUT_MANIFEST));
  let old = null;
  if (oldRaw !== null) {
    try { old = JSON.parse(oldRaw); } catch { old = null; }
  }
  let written = 0;
  for (const [relative, content] of [...outputs].sort(([left], [right]) => left.localeCompare(right))) {
    const filename = resolveInside(root, relative);
    const current = await readOrNull(filename);
    if (current === content) continue;
    await mkdir(path.dirname(filename), { recursive: true });
    await writeFile(filename, content);
    ++written;
  }
  if (old && Array.isArray(old.outputs)) {
    const owned = new Set(outputs.keys());
    for (const entry of old.outputs) {
      if (typeof entry?.path !== 'string' || owned.has(entry.path)) continue;
      const filename = resolveInside(root, entry.path);
      await rm(filename, { force: true });
    }
  }
  const manifest = manifestFor(outputs);
  const manifestPath = resolveInside(root, OUTPUT_MANIFEST);
  await mkdir(path.dirname(manifestPath), { recursive: true });
  await writeFile(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
  return { written, manifest: manifest.outputs.length };
}
