export function generateDropChancesHeader(derived) {
  const lines = [
    '// Generated by tools/generate.mjs from schema/catalogs/drop-rules.json and the entity catalog.',
    '// This is product simulation data; it is not compared with archived wasm at build time.',
    '#pragma once',
    '#include <cstddef>',
    '#include <cstdint>',
    '',
    'namespace engine::catalog {',
    'struct DropChance {',
    '  std::uint16_t petalTypeId;',
    '  float chance;',
    '};',
    '',
    'struct EntityDropTable {',
    '  std::uint16_t typeId;',
    '  const DropChance* drops;',
    '  std::uint8_t dropCount;',
    '  std::uint16_t aliasOf;',
    '};',
    '',
  ];
  for (const entity of derived.entities) {
    if (entity.drops.length === 0) continue;
    lines.push(`inline constexpr DropChance kEntityDrops_${entity.typeId}[] = {`);
    for (const drop of entity.drops)
      lines.push(`  {${drop.petalTypeId}, ${cppFloat(drop.chance)}},`);
    lines.push('};');
  }
  lines.push('');
  lines.push(`inline constexpr EntityDropTable kEntityDropTables[] = {`);
  for (const entity of derived.entities) {
    const pointer = entity.drops.length > 0 ? `kEntityDrops_${entity.typeId}` : 'nullptr';
    lines.push(`  {${entity.typeId}, ${pointer}, ${entity.drops.length}, ${entity.aliasOf ?? 0}},`);
  }
  lines.push('};');
  lines.push(`static_assert(std::size(kEntityDropTables) == ${derived.entities.length});`);
  lines.push('');
  lines.push(`inline constexpr double kDropAreaMix[${derived.constants.areaMix.length}] = {`);
  lines.push(`  ${derived.constants.areaMix.join(', ')},`);
  lines.push('};');
  lines.push(`inline constexpr double kPetalDropMass[${derived.constants.petalDropMass.length}] = {`);
  lines.push(`  ${derived.constants.petalDropMass.join(', ')},`);
  lines.push('};');
  lines.push(`inline constexpr std::uint16_t kDropReferenceSpecies = ${derived.constants.referenceSpecies};`);
  lines.push(`inline constexpr double kDropReferenceMass = ${derived.constants.referenceMass};`);
  lines.push('} // namespace engine::catalog');
  return lines.join('\n') + '\n';
}

