function descriptionArray(prefix, descriptions) {
  const lines = [];
  for (const [index, description] of descriptions.entries()) {
    lines.push(`inline constexpr const char* const ${prefix}${index} = ${cppString(description)};`);
  }
  if (descriptions.length === 0) {
    lines.push(`inline constexpr const char* const ${prefix}None = "";`);
  }
  const names =
    descriptions.length === 0
      ? [`${prefix}None`]
      : descriptions.map((_, index) => `${prefix}${index}`);
  lines.push(`inline constexpr const char* const ${prefix}Values[] = {${names.join(', ')}};`);
  return lines.join('\n');
}

export function generateCatalogData({ petals, entities, spawnRules, counts }) {
  const lines = [
    '// Generated by tools/generate.mjs from schema/catalogs/*.json. Do not edit.',
    '#pragma once',
    '#include "engine/catalog/catalog_types.hpp"',
    '#include <array>',
    '#include <cstddef>',
    '#include <cstdint>',
    '#include <iterator>',
    '',
    'namespace engine::catalog {',
    `inline constexpr std::size_t kPetalCount = ${counts.petals};`,
    `inline constexpr std::size_t kEntityCount = ${counts.entities};`,
    `inline constexpr std::size_t kSpawnRuleCount = ${counts.spawnRules};`,
    `inline constexpr std::size_t kStringCount = ${counts.strings};`,
    '',
  ];
  for (const petal of petals) {
    lines.push(descriptionArray(`kPetal${petal.typeId}Descriptions`, petal.descriptions));
  }
  for (const entity of entities) {
    lines.push(descriptionArray(`kEntity${entity.typeId}Descriptions`, entity.descriptions));
  }
  lines.push('');

  lines.push('inline constexpr std::array<PetalCatalogEntry, kPetalCount> kPetals{{');
  for (const petal of petals) {
    lines.push(
      `  {${petal.typeId}, ${cppString(petal.name)}, kPetal${petal.typeId}DescriptionsValues, ${petal.descriptions.length}, ${petal.rarityIndex}, ${cppFloat(petal.rechargeMilliseconds)}, ${petal.instancesPerSlot}, ${cppFloat(petal.labelFontSize)}, ${cppFloat(petal.drawRadius)}, ${cppFloat(petal.collisionRadius)}, ${cppFloat(petal.damage)}, ${cppFloat(petal.health)}, ${bool(petal.orbitHidden)}, ${bool(petal.sharedOrbit)}, ${cppFloat(petal.extraOrbitRadius)}},`,
    );
  }
  lines.push('}};', '');

  for (const entity of entities) {
    if (entity.petalTypeIds.length > 0) {
      lines.push(
        `inline constexpr std::array<std::uint32_t, ${entity.petalTypeIds.length}> kEntity${entity.typeId}PetalIds{{${entity.petalTypeIds.join(', ')}}};`,
      );
    }
  }
  lines.push('inline constexpr std::array<EntityCatalogEntry, kEntityCount> kEntities{{');
  for (const entity of entities) {
    const pointer =
      entity.petalTypeIds.length > 0 ? `kEntity${entity.typeId}PetalIds.data()` : 'nullptr';
    lines.push(
      `  {${entity.typeId}, ${cppString(entity.name)}, kEntity${entity.typeId}DescriptionsValues, ${entity.descriptions.length}, ${entity.rarity}, ${cppFloat(entity.scale)}, ${pointer}, ${entity.petalTypeIds.length}, ${entity.dropDrawCount}, ${entity.dropAliasOf}, ${cppFloat(entity.dropWeight)}},`,
    );
  }
  lines.push('}};', '');

  for (const [index, rule] of spawnRules.entries()) {
    lines.push(
      `inline constexpr std::array<std::uint8_t, ${rule.regionIds.length}> kSpawnRule${index}Regions{{${rule.regionIds.join(', ')}}};`,
    );
  }
  lines.push('inline constexpr std::array<SpawnRuleCatalogEntry, kSpawnRuleCount> kSpawnRules{{');
  for (const [index, rule] of spawnRules.entries()) {
    lines.push(
      `  {${cppFloat(rule.weight)}, kSpawnRule${index}Regions.data(), ${rule.regionIds.length}, ${rule.entityTypeId}},`,
    );
  }
  lines.push('}};', '');
  lines.push('static_assert(std::size(kPetals) == kPetalCount);');
  lines.push('static_assert(std::size(kEntities) == kEntityCount);');
  lines.push('static_assert(std::size(kSpawnRules) == kSpawnRuleCount);');
  lines.push('} // namespace engine::catalog');
  return lines.join('\n') + '\n';
}

