/** Generated named state bits shared by the engine and client. */
export function generateStateFlagsHeader(groups) {
  const lines = [
    '// Generated by tools/generate.mjs from schema/catalogs/state-flags.json. Do not edit.',
    '#pragma once',
    '#include <cstdint>',
    '#include <iterator>',
    '',
    'namespace engine {',
  ];
  for (const group of groups) {
    const type = group.bits === 8 ? 'std::uint8_t' : 'std::uint32_t';
    lines.push(`enum class ${group.symbol} : ${type} {`);
    for (const flag of group.flags) {
      lines.push(`  k${flag.symbol} = 1U << ${flag.bit},`);
    }
    lines.push('};', '');
  }
  lines.push('}  // namespace engine');
  return lines.join('\n') + '\n';
}

