/** Apply the small, reasoned display-difference layer to derived drop rows. */
export function applyGalleryOverrides(derived, overrides, entities) {
  const rarityById = new Map(entities.map(entity => [entity.typeId, entity.rarity]));
  const byType = new Map(derived.entities.map(entity => [entity.typeId, {
    typeId: entity.typeId,
    rarity: rarityById.get(entity.typeId),
    drops: entity.drops.map(drop => ({ ...drop })),
  }]));
  for (const override of overrides) {
    const entry = byType.get(override.typeId);
    if (entry === undefined) throw new Error(`gallery override for unknown entity ${override.typeId}`);
    if (override.rarity !== undefined) entry.rarity = override.rarity;
    if (override.removeDrops !== undefined) {
      const remove = new Set(override.removeDrops);
      entry.drops = entry.drops.filter(drop => !remove.has(drop.petalTypeId));
    }
    if (override.replaceDrops !== undefined) entry.drops = override.replaceDrops.map(drop => ({ ...drop }));
    if (override.addDrops !== undefined) entry.drops.push(...override.addDrops.map(drop => ({ ...drop })));
    entry.drops.sort((left, right) => right.chance - left.chance);
  }
  return [...byType.values()];
}

export function generateMobGalleryTs(derived, overrides, catalogEntities) {
  const entities = applyGalleryOverrides(derived, overrides, catalogEntities);
  const rows = entities.filter(entry => entry.typeId > 0).map(entry => `  ${entry.typeId}: { rarity: ${entry.rarity}, drops: [${entry.drops.map(drop => `{ petalTypeId: ${drop.petalTypeId}, chance: ${drop.chance} }`).join(', ')}] },`);
  return `/** Generated by tools/generate.mjs from drop-rules.json and gallery-overrides.json. */
export interface MobGalleryDrop { readonly petalTypeId: number; readonly chance: number; }
export interface MobGalleryInfo { readonly rarity: number; readonly drops: readonly MobGalleryDrop[]; }
export const MOB_GALLERY: Readonly<Record<number, MobGalleryInfo>> = {
${rows.join('\n')}
};
`;
}

