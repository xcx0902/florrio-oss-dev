/** Pure catalog/menu view rendering. No writes and no archived inputs. */

/** Type id 0 means "no published type"; gallery rows start at 1. */
const NO_TYPE_ID = 0;

const cppFloat = (value) => {
  if (typeof value !== 'number' || !Number.isFinite(value)) {
    throw new Error(`invalid float ${value}`);
  }
  return Number.isInteger(value) ? `${value.toFixed(1)}F` : `${value}F`;
};
const cppString = (value) => {
  if (typeof value !== 'string') {
    throw new Error('expected string');
  }
  return JSON.stringify(value);
};
const bool = (value) => (value ? 'true' : 'false');
const byType = (rows) => new Map(rows.map((row) => [row.typeId, row]));
const requireCombat = (petal, combatById) => {
  const combat = combatById.get(petal.typeId);
  if (combat === undefined) {
    throw new Error(`petal ${petal.typeId} has no combat record`);
  }
  return combat;
};

/** Join the base petal identity with the combat-owned numeric fields. */
export function petalViews(petals, petalCombat) {
  const combatById = byType(petalCombat);
  return petals.map((petal) => {
    const combat = requireCombat(petal, combatById);
    return {
      ...petal,
      drawRadius: combat.drawRadius,
      collisionRadius: combat.collisionRadius,
      damage: combat.damage,
      health: combat.health,
      behavior: combat.behavior,
      healAmount: combat.healAmount,
      orbitProfile: combat.orbitProfile,
    };
  });
}

/** Generated C++ identity views. Symbols are the stable product names; numeric
 * ids remain owned by petals.json/entities.json and are never renumbered here. */
export function generateCatalogIdsHeader(rarities, petals, entities, behaviors) {
  const lines = [
    '// Generated by tools/generate.mjs from schema/catalogs/{rarities,petals,entities,petal-combat}.json.',
    '// Do not edit by hand; rerun `npm run schema:generate`.',
    '#pragma once',
    '#include <cstdint>',
    '#include <iterator>',
    '',
    'namespace engine::catalog {',
    '',
    'enum class Rarity : std::uint8_t {',
  ];
  for (const rarity of rarities) {
    lines.push(`  k${rarity.symbol} = ${rarity.index},`);
  }
  lines.push('};', '', 'enum class PetalId : std::uint16_t {');
  for (const petal of petals) {
    lines.push(`  k${petal.symbol} = ${petal.typeId},`);
  }
  lines.push('};', '', 'enum class SpeciesId : std::uint16_t {');
  for (const entity of entities) {
    lines.push(`  k${entity.symbol} = ${entity.typeId},`);
  }
  lines.push('};', '', 'enum class PetalBehavior : std::uint8_t {');
  for (const [index, behavior] of behaviors.entries()) {
    lines.push(`  k${behavior.symbol} = ${index},`);
  }
  lines.push(
    '};',
    '',
    '[[nodiscard]] constexpr PetalId petal_id(std::uint16_t type_id) {',
    '  return static_cast<PetalId>(type_id);',
    '}',
    '[[nodiscard]] constexpr SpeciesId species_id(std::uint16_t type_id) {',
    '  return static_cast<SpeciesId>(type_id);',
    '}',
    '[[nodiscard]] constexpr std::uint16_t petal_type_id(PetalId id) {',
    '  return static_cast<std::uint16_t>(id);',
    '}',
    '[[nodiscard]] constexpr std::uint16_t species_type_id(SpeciesId id) {',
    '  return static_cast<std::uint16_t>(id);',
    '}',
    '[[nodiscard]] constexpr std::uint8_t rarity_index(Rarity rarity) {',
    '  return static_cast<std::uint8_t>(rarity);',
    '}',
    '',
    '}  // namespace engine::catalog',
  );
  return lines.join('\n') + '\n';
}

