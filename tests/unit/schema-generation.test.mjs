async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const filename = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(filename));
    else if (entry.isFile()) files.push(filename);
  }
  return files;
}

async function treeHash(directory) {
  const files = (await walk(directory)).sort();
  const hash = createHash('sha256');
  for (const file of files) {
    hash.update(path.relative(directory, file));
    hash.update('\0');
    hash.update(await readFile(file));
    hash.update('\0');
  }
  return hash.digest('hex');
}

async function outputsHash(directory) {
  const manifest = JSON.parse(await readFile(path.join(directory, 'schema/generated-outputs.json'), 'utf8'));
  const hash = createHash('sha256');
  for (const entry of manifest.outputs.map(entry => entry.path).sort()) {
    hash.update(entry);
    hash.update('\0');
    hash.update(await readFile(path.join(directory, entry)));
    hash.update('\0');
  }
  return hash.digest('hex');
}

function run(cwd, args = []) {
  return spawnSync(process.execPath, [generator, ...args], { cwd, encoding: 'utf8' });
}

async function inputFixture(name) {
  const fixture = path.join(temporary, name);
  for (const relative of Object.values(SCHEMA_INPUTS)) {
    const target = path.join(fixture, relative);
    await mkdir(path.dirname(target), { recursive: true });
    await cp(path.join(root, relative), target);
  }
  return fixture;
}

test('product generator check passes and is read-only', async () => {
  const before = await treeHash(path.join(root, 'schema'));
  const result = run(root, ['--check']);
  assert.equal(result.status, 0, result.stderr);
  assert.match(result.stdout, /"mode":"check"/);
  assert.equal(await treeHash(path.join(root, 'schema')), before);
});

test('generator produces identical bytes twice and check rejects stale, missing and unregistered outputs', async () => {
  const fixture = await inputFixture('roundtrip');
  const first = run(fixture);
  assert.equal(first.status, 0, first.stderr);
  const firstTree = await treeHash(fixture);
  const second = run(fixture);
  assert.equal(second.status, 0, second.stderr);
  assert.match(second.stdout, /"written":0/);
  assert.equal(await treeHash(fixture), firstTree);
  assert.equal(run(fixture, ['--check']).status, 0);

  const stale = path.join(fixture, 'client/src/schema/petals.ts');
  await writeFile(stale, '// stale\n');
  const beforeCheck = await treeHash(fixture);
  const staleResult = run(fixture, ['--check']);
  assert.notEqual(staleResult.status, 0);
  assert.match(staleResult.stderr, /stale/);
  assert.equal(await treeHash(fixture), beforeCheck, 'check must not repair or rewrite');

  await rm(stale);
  const missing = run(fixture, ['--check']);
  assert.notEqual(missing.status, 0);
  assert.match(missing.stderr, /missing/);

  await writeFile(stale, await readFile(path.join(root, 'client/src/schema/petals.ts')));
  const extra = path.join(fixture, 'schema/generated/extra.json');
  await writeFile(extra, '// Generated by tools/generate.mjs\n{}\n');
  const extraResult = run(fixture, ['--check']);
  assert.notEqual(extraResult.status, 0);
  assert.match(extraResult.stderr, /unregistered generated output/);
});

test('generator validates every input before writing and removes only manifest-registered stale outputs', async () => {
  const fixture = await inputFixture('validation');
  assert.equal(run(fixture).status, 0);
  const beforeFailure = await outputsHash(fixture);
  const petalsFile = path.join(fixture, 'schema/catalogs/petals.json');
  const petals = JSON.parse(await readFile(petalsFile, 'utf8'));
  petals.petals[1].typeId = 0;
  await writeFile(petalsFile, JSON.stringify(petals));
  const failed = run(fixture);
  assert.notEqual(failed.status, 0);
  assert.match(failed.stderr, /duplicate|dense/i);
  assert.equal(await outputsHash(fixture), beforeFailure, 'failed validation changed no generated file');

  // Restore the input and register one obsolete output, then regenerate.
  await cp(path.join(root, 'schema/catalogs/petals.json'), petalsFile);
  const obsolete = path.join(fixture, 'schema/generated/obsolete.json');
  await writeFile(obsolete, '{"old":true}\n');
  const manifestFile = path.join(fixture, 'schema/generated-outputs.json');
  const manifest = JSON.parse(await readFile(manifestFile, 'utf8'));
  manifest.outputs.push({ path: 'schema/generated/obsolete.json', bytes: 12, sha256: '0' });
  await writeFile(manifestFile, JSON.stringify(manifest, null, 2) + '\n');
  assert.equal(run(fixture).status, 0);
  await assert.rejects(readFile(obsolete), /ENOENT/);
  assert.equal(run(fixture, ['--check']).status, 0);
});

test('transport requires exactly 512 hex characters and generated keys round-trip the XOR', async () => {
  const inputs = await loadSchemaInputs(root);
  const key = validateTransport(inputs.transport);
  assert.equal(key.length, 256);
  for (const mutate of [
    value => { value.packetXor.keyHex = value.packetXor.keyHex.slice(1); },
    value => { value.packetXor.keyHex += '00'; },
    value => { value.packetXor.keyHex = 'zz' + value.packetXor.keyHex.slice(2); },
    value => { value.packetXor.bytes = 255; },
    value => { value.packetXor.algorithm = 'add'; },
    value => { value.packetXor.encoding = 'base64'; },
  ]) {
    const copy = structuredClone(inputs.transport);
    mutate(copy);
    assert.throws(() => validateTransport(copy), /transport:/);
  }
  const cpp = await readFile(path.join(root, 'engine/include/engine/net/packet_key.hpp'), 'utf8');
  const ts = await readFile(path.join(root, 'client/src/schema/packet-key.ts'), 'utf8');
  const cppBytes = [...cpp.matchAll(/0x([0-9a-f]{2})/g)].map(match => Number.parseInt(match[1], 16));
  const tsBytes = [...ts.matchAll(/0x([0-9a-f]{2})/g)].map(match => Number.parseInt(match[1], 16));
  assert.deepEqual(cppBytes, [...key]);
  assert.deepEqual(tsBytes, [...key]);
  const payload = Uint8Array.from([1, 2, 3, 4, 255]);
  assert.deepEqual(applyPacketXor(applyPacketXor(payload, key), key), payload);
});

test('drop derivation is deterministic and keeps the product reference mass and Rock rows', async () => {
  const inputs = await loadSchemaInputs(root);
  const derived = deriveDropChances({
    entities: inputs.entities.entities,
    spawnRules: inputs.spawnRules.rules,
    petals: inputs.petals.petals,
    rules: inputs.dropRules,
  });
  assert.equal(derived.constants.referenceMass, 7.031205701793481e-7);
  assert.deepEqual(derived.entities.find(entity => entity.typeId === 1).drops, [
    { petalTypeId: 4, chance: 0.00522140646353364 },
    { petalTypeId: 2, chance: 0.034809377044439316 },
    { petalTypeId: 3, chance: 0.10442813485860825 },
  ]);
  assert.equal(derived.entities.reduce((sum, entity) => sum + entity.drops.length, 0), 102);
  assert.deepEqual(derived.entities.find(entity => entity.typeId === 16).drops,
    derived.entities.find(entity => entity.typeId === 15).drops);
});

test('drop aliases resolve through a chain regardless of input order', async () => {
  const inputs = await loadSchemaInputs(root);
  const entities = structuredClone(inputs.entities.entities);
  const byId = id => entities.find(entity => entity.typeId === id);
  byId(16).dropAliasOf = 18;
  byId(18).dropAliasOf = 17;
  const derived = deriveDropChances({
    entities,
    spawnRules: inputs.spawnRules.rules,
    petals: inputs.petals.petals,
    rules: inputs.dropRules,
  });
  const drops = id => derived.entities.find(entity => entity.typeId === id).drops;
  assert.ok(drops(17).length > 0);
  assert.deepEqual(drops(16), drops(17));
  assert.deepEqual(drops(18), drops(17));
});

test('drop rules reject missing ids, alias cycles, illegal floats and zero denominators', async () => {
  const inputs = await loadSchemaInputs(root);
  const base = {
    entities: structuredClone(inputs.entities.entities),
    spawnRules: structuredClone(inputs.spawnRules.rules),
    petals: structuredClone(inputs.petals.petals),
    rules: structuredClone(inputs.dropRules),
  };
  const cases = [
    value => { value.entities[1].petalTypeIds.push(999); },
    value => { value.entities[1].dropAliasOf = 2; value.entities[2].dropAliasOf = 1; },
    value => { value.entities[1].dropWeight = Number.NaN; },
    value => { value.rules.areaMix.fill(0); },
    value => { value.rules.children['1'] = [[999, 1]]; },
  ];
  for (const mutate of cases) {
    const copy = structuredClone(base);
    mutate(copy);
    assert.throws(() => validateDropInputs(copy), /drop rules:/);
    assert.throws(() => deriveDropChances(copy), /drop rules:/);
  }
});

